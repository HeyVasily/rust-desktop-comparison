#!/usr/bin/env python3
"""Render data/features.json into GitHub-readable Markdown.

Writes docs/features.md and the compact matrix between the
<!-- features:start --> / <!-- features:end --> markers in README.md.
Use --check in CI to fail when the generated files are stale.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "features.json"
FEATURES_MD = ROOT / "docs" / "features.md"
README = ROOT / "README.md"
START = "<!-- features:start -->"
END = "<!-- features:end -->"
OS_SHORT = {"windows": "Win", "macos": "mac", "linux": "Linux"}


def link(source: str, from_dir: str) -> str:
    """Return a Markdown link target relative to the rendering file."""
    if source.startswith("http"):
        return source
    return f"{from_dir}{source}"


def cell_symbols(data: dict, cell: dict, sep: str = "<br>") -> str:
    levels = data["levels"]
    if "text" in cell:
        return cell["text"]
    per_os = cell.get("os")
    if per_os and len(set(per_os.values())) > 1:
        return sep.join(
            f"{levels[per_os[os]]['symbol']} {OS_SHORT[os]}" for os in data["os"] if os in per_os
        )
    return levels[cell["level"]]["symbol"]


def legend(data: dict) -> str:
    return " · ".join(f"{v['symbol']} {v['label']}" for v in data["levels"].values())


def render_full(data: dict) -> str:
    fws = data["frameworks"]
    out = [
        "<!-- Generated by tools/render_features.py from data/features.json. Do not edit. -->",
        "# Native features and OS integration",
        "",
        f"Checked {data['checked']}. {data['about']}",
        "",
        f"Legend: {legend(data)}. Where systems differ, each system is marked separately.",
        "Evidence **repo** points to this repository (lockfile, example or capture);",
        "**docs** points to upstream documentation or release notes.",
        "The same data drives the [interactive page](https://heyvasily.github.io/rust-desktop-comparison/#features).",
        "",
        "| Framework | Version here | Language | UI model |",
        "| --- | --- | --- | --- |",
    ]
    for fw in fws:
        out.append(
            f"| [{fw['name']}]({fw['home']}) | {fw['version']} | {fw['language']} | {fw['model']} |"
        )
    for group in data["groups"]:
        out += ["", f"## {group['title']}", ""]
        out.append("| Capability | " + " | ".join(fw["name"] for fw in fws) + " |")
        out.append("| --- |" + " --- |" * len(fws))
        for feat in group["features"]:
            cells = []
            for fw in fws:
                c = feat["support"][fw["id"]]
                cells.append(cell_symbols(data, c))
            out.append(f"| **{feat['title']}** | " + " | ".join(cells) + " |")
        for feat in group["features"]:
            if feat.get("kind") == "text":
                continue
            out += ["", f"### {feat['title']}", "", feat["description"], ""]
            for fw in fws:
                c = feat["support"][fw["id"]]
                sym = cell_symbols(data, c, " · ")
                ev = c["evidence"]
                out.append(
                    f"- **{fw['name']}** {sym} — {c['note']} "
                    f"([{ev}]({link(c['source'], '../')}))"
                )
    out += [
        "",
        "## Corrections",
        "",
        "Edit [`data/features.json`](../data/features.json), cite a source, and run",
        "`python3 tools/render_features.py`.",
        "",
    ]
    return "\n".join(out)


def render_compact(data: dict) -> str:
    fws = data["frameworks"]
    out = [
        START,
        "<!-- Generated by tools/render_features.py from data/features.json. -->",
        "| Capability | " + " | ".join(fw["name"] for fw in fws) + " |",
        "| --- |" + " :---: |" * len(fws),
    ]
    for group in data["groups"]:
        for feat in group["features"]:
            if feat.get("kind") == "text":
                continue
            cells = [cell_symbols(data, feat["support"][fw["id"]]) for fw in fws]
            out.append(f"| {feat['title']} | " + " | ".join(cells) + " |")
    out += ["", f"{legend(data)}. Checked {data['checked']}.", END]
    return "\n".join(out)


def splice_readme(text: str, block: str) -> str:
    start, end = text.find(START), text.find(END)
    if start < 0 or end < 0:
        raise SystemExit("README.md lacks the features markers")
    return text[:start] + block + text[end + len(END):]


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if outputs are stale")
    args = parser.parse_args()
    data = json.loads(DATA.read_text(encoding="utf-8"))
    validate(data)
    outputs = {
        FEATURES_MD: render_full(data),
        README: splice_readme(README.read_text(encoding="utf-8"), render_compact(data)),
    }
    stale = [p for p, text in outputs.items() if not p.exists() or p.read_text(encoding="utf-8") != text]
    if args.check:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1 if stale else 0
    for p in stale:
        p.write_text(outputs[p], encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)}")
    return 0


def validate(data: dict) -> None:
    ids = [fw["id"] for fw in data["frameworks"]]
    for group in data["groups"]:
        for feat in group["features"]:
            missing = set(ids) - set(feat["support"])
            if missing:
                raise SystemExit(f"{feat['id']}: missing {sorted(missing)}")
            for fw, c in feat["support"].items():
                if not c.get("source"):
                    raise SystemExit(f"{feat['id']}/{fw}: missing source")
                if feat.get("kind") == "text":
                    continue
                levels = [c["level"], *c.get("os", {}).values()]
                bad = [lv for lv in levels if lv not in data["levels"]]
                if bad:
                    raise SystemExit(f"{feat['id']}/{fw}: unknown level {bad}")
                if c["evidence"] not in ("docs", "repo"):
                    raise SystemExit(f"{feat['id']}/{fw}: evidence must be docs or repo")
                if c["evidence"] == "repo" and not (ROOT / c["source"].split("#")[0]).exists():
                    raise SystemExit(f"{feat['id']}/{fw}: missing file {c['source']}")


if __name__ == "__main__":
    sys.exit(main())
